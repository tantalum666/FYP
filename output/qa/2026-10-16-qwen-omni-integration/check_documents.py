"""Check setup documentation and reading provenance without reading any secret file."""

import hashlib
import json
import re
import subprocess
from datetime import datetime, timezone
from difflib import SequenceMatcher
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[3]
QA = Path(__file__).resolve().parent
BASE = "2249df246b8d9380dbf0823895c36fee5647f4d0"
PRIOR = "output/qa/2026-10-16-qwen-key-setup/reading-inventory.json"
old = {x["path"]: x for x in json.loads((QA / "reading-inventory.json").read_text())["files"]}
paths = sorted(subprocess.check_output([
    "rg", "--files", "--hidden", "-g", "*.md", "-g", "!**/.git/**",
    "-g", "!**/node_modules/**", "-g", "!**/.venv/**", "-g", "!**/__pycache__/**",
    "-g", "!**/.pytest_cache/**", "-g", "!**/.cache/**", "-g", "!**/dist/**",
    "-g", "!**/build/**", "-g", "!output/qa/**",
], cwd=ROOT, text=True).splitlines())
files = []
for rel in paths:
    p = ROOT / rel
    before = subprocess.run(["git", "show", f"{BASE}:{rel}"], cwd=ROOT, capture_output=True)
    if before.returncode:
        assert rel == "desk-companion/docs/qwen-omni.md", rel
        initial = []
    else:
        item = old[rel]
        assert hashlib.sha256(before.stdout).hexdigest() == item.get("sha256", item.get("sha256_before")), rel
        initial = before.stdout.decode().splitlines()
    current = p.read_text().splitlines()
    inherited, authored = [], []
    for tag, i, j, a, b in SequenceMatcher(None, initial, current, autojunk=False).get_opcodes():
        if tag == "equal" and b > a:
            inherited.append({"current": [a + 1, b], "prior": [i + 1, j]})
        elif b > a:
            authored.append([a + 1, b])
    files.append({
        "path": rel, "lines": len(current),
        "sha256_before": hashlib.sha256(before.stdout).hexdigest() if initial else None,
        "sha256_after": hashlib.sha256(p.read_bytes()).hexdigest(),
        "inherited_exact_ranges": inherited, "authored_and_reviewed_ranges": authored,
    })
record = {
    "scope": "Same ongoing selected-model to Omni implementation workflow; inherited observed text plus relevant rereads and authored changes, not a new independent full read.",
    "base_commit": BASE, "inherited_read_record": PRIOR,
    "exclusions": [".git", "dependencies/caches/third-party packages", "build outputs", "output/qa autogenerated evidence"],
    "focused_reread": ["AGENTS.md", "product.md", "handoff.md", "latest related decision-log", "current setup/operator/software and tooling architecture/README", "voice.py EOF and new modules", "AssistantPanel.tsx/audio.ts/types.ts EOF", "Omni tests EOF and existing voice/tool fixtures", "latest voice/computer research and latency plan"],
    "live_trial_authorization": {"maximum_cny":5,"inputs":"synthetic audio, fictional calendar, generated JPEG only; no real mic or screen"},
    "referenced_chat": {"thread_id":"01a07aeb-a256-7572-a42e-bd7e4668674f","read_thread_called":True,"recent_turns_read":3,"scope":"earlier art continuation; failed statuses not completion evidence"},
    "files": files, "completed_at": datetime.now(timezone.utc).isoformat(),
}
(QA / "reading-inventory.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n")
(QA / "document-checks.json").write_text("{}\n")
missing, generated, bad_groups = [], [], []
count = 0
checked = paths + [str((QA / "verification.md").relative_to(ROOT))]
for rel in checked:
    p = ROOT / rel
    body = p.read_text()
    if re.search(r"\bGroup\s*(?:[013-9]|2\d)\b", body):
        bad_groups.append(rel)
    for raw in re.findall(r"\[[^\]]*\]\((<[^>]+>|[^)\n]+)\)", body):
        target = raw.strip().strip("<>")
        if re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target) or target.startswith("#"):
            continue
        target = unquote(target.split("#", 1)[0].split("?", 1)[0])
        if not target:
            continue
        count += 1
        if not (p.parent / target).exists():
            item = {"file": rel, "target": target}
            (generated if item == {"file": "desk-companion/README.md", "target": ".runtime/credentials.json"} else missing).append(item)
assert (ROOT / "planning/2026-09-14/group-2-details.json").is_file()
changed = subprocess.check_output(["git", "diff", "--name-only", BASE], cwd=ROOT, text=True).splitlines()
allowed_code = {
    "desk-companion/backend/desk/voice.py",
    "desk-companion/backend/desk/voice_credentials.py",
    "desk-companion/backend/desk/voice_media.py",
    "desk-companion/config/service.env.example",
    "desk-companion/frontend/src/workspace/AssistantPanel.tsx",
    "desk-companion/frontend/src/workspace/audio.ts",
    "desk-companion/frontend/src/workspace/types.ts",
    "desk-companion/frontend/src/workspace/vision.ts",
    "desk-companion/frontend/tests/voice-vision.test.ts",
    "desk-companion/tests/test_voice_omni.py",
    "desk-companion/tests/fixtures/qwen-vision.jpg",
}
assert all(p.endswith(".md") or p in allowed_code or p.startswith("output/qa/") for p in changed), changed
subprocess.run(["git", "diff", "--check", BASE], cwd=ROOT, check=True)
result = {"project_markdown_versions": len(files), "documents_checked": len(checked), "local_references": count, "resolved": count-len(missing)-len(generated), "broken_links": missing, "expected_generated_targets": generated, "wrong_group_names": bad_groups, "identity_source_exists": True, "outside_allowed_code_paths_diff": [], "school_and_art_binary_changes": [], "whitespace": "passed"}
(QA / "document-checks.json").write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result))
assert not missing and not bad_groups
