"""Bounded, owner-only lexical retrieval of retained work metadata.

This service has no index, reconciliation, file-body reader or dispatch surface.
The final authority check uses a new transaction, not the corpus read snapshot.
"""

import hashlib
import json
import re
import sqlite3
import unicodedata
from datetime import UTC, datetime
from typing import Annotated, Literal

from fastapi import APIRouter, Depends, Request
from pydantic import Field, field_validator, model_validator

from .file_store import ID, require_access, session_from_request
from .schemas import StrictModel
from .store import DomainError, encode

RUN_CAP = 100
SOURCE_CAP = 100
ARTIFACT_CAP = 400
CORPUS_CAP = RUN_CAP + SOURCE_CAP + ARTIFACT_CAP
FORMATS = {"text", "markdown", "csv", "json"}
RUN_STATES = {
    "queued",
    "planning",
    "running",
    "waiting_input",
    "waiting_review",
    "paused",
    "blocked",
    "succeeded",
    "partial",
    "failed",
    "cancelled",
}
# Run IDs generated by the coordinator are hex; historical standalone publishers
# may have retained short opaque scope IDs. Paths and control characters are not IDs.
SCOPE_ID = re.compile(r"^[A-Za-z0-9_-]{1,100}$")

SearchKind = Literal["all", "run", "artifact", "source"]
MatchField = Literal["id", "title", "source_name", "current_linked_goal"]
MatchReason = Literal["browse", "exact_id", "exact_title", "phrase", "all_terms", "linked_metadata"]
FileFormat = Literal["text", "markdown", "csv", "json"]


class WorkSearchInput(StrictModel):
    query: str = Field(default="", max_length=200, strict=True)
    kind: SearchKind = "all"
    limit: int = Field(default=20, ge=1, le=50, strict=True)
    offset: int = Field(default=0, ge=0, le=CORPUS_CAP, strict=True)
    snapshot: str | None = Field(default=None, pattern=r"^[a-f0-9]{64}$", strict=True)

    @field_validator("query", mode="before")
    @classmethod
    def trim(cls, value):
        # Bound raw input as well as the normalized query. Reject surrogate text
        # that cannot safely participate in canonical UTF-8 fingerprints.
        if isinstance(value, str):
            if len(value) > 200 or any(0xD800 <= ord(c) <= 0xDFFF for c in value):
                raise ValueError("Use at most 200 Unicode characters")
            return value.strip()
        return value

    @model_validator(mode="after")
    def page_binding(self):
        if self.offset and self.snapshot is None:
            raise ValueError("Subsequent pages require the original snapshot")
        return self


class SearchHit(StrictModel):
    id: str
    title: str
    timestamp: str | None
    matched_fields: list[MatchField]
    match_reason: MatchReason


class RunSearchHit(SearchHit):
    kind: Literal["run"]
    state: str
    version: int | None
    mode: Literal["deterministic", "model"] | None
    plan_revision: int | None
    source_names: list[str]


class FileSearchHit(SearchHit):
    format: FileFormat | None
    byte_count: int | None
    recorded_status: Literal["verified", "unknown"]


class SourceSearchHit(FileSearchHit):
    kind: Literal["source"]
    revision: Literal[1]


class ArtifactSearchHit(FileSearchHit):
    kind: Literal["artifact"]
    run_id: str | None
    current_linked_goal: str | None
    output_membership: Literal["current", "earlier", "unknown", "unlinked"]
    source_names: list[str]


class WorkSearchResult(StrictModel):
    items: list[
        Annotated[RunSearchHit | SourceSearchHit | ArtifactSearchHit, Field(discriminator="kind")]
    ]
    total: int
    snapshot: str
    next_offset: int | None
    search_scope: Literal["local_metadata"] = "local_metadata"
    ranking: Literal["lexical_v1"] = "lexical_v1"
    file_status_basis: Literal["last_recorded"] = "last_recorded"


def normalize(value):
    return " ".join(unicodedata.normalize("NFKC", value).casefold().split())


def text(value, maximum, *, filename=False):
    if (
        not isinstance(value, str)
        or len(value) > maximum
        or any(0xD800 <= ord(c) <= 0xDFFF or ord(c) == 0 for c in value)
        or filename
        and any(ord(c) < 32 or c in "/\\" for c in value)
    ):
        return ""
    return value


def integer(value, minimum=0, maximum=2**53 - 1):
    return value if type(value) is int and minimum <= value <= maximum else None


def timestamp(value):
    if not isinstance(value, str) or len(value) > 40:
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            return None
        return parsed.astimezone(UTC).isoformat().replace("+00:00", "Z")
    except (ValueError, OverflowError):
        return None


def id_list(value, maximum):
    # Invalid/missing current membership must never turn an old output into an
    # earlier/current claim. Treat the whole malformed list as unknown.
    if (
        not isinstance(value, list)
        or len(value) > maximum
        or any(not isinstance(v, str) or not ID.fullmatch(v) for v in value)
        or len(set(value)) != len(value)
    ):
        return None
    return value


def decode_projection(value):
    if not isinstance(value, str) or len(value.encode("utf-8")) > 64 * 1024:
        raise DomainError("WORK_SEARCH_METADATA_INVALID", 409)
    try:
        result = json.loads(value)
    except (ValueError, RecursionError):
        raise DomainError("WORK_SEARCH_METADATA_INVALID", 409) from None
    if not isinstance(result, dict):
        raise DomainError("WORK_SEARCH_METADATA_INVALID", 409)
    return result


def projection(column, fields):
    """Only code-owned column/field literals enter this SQL expression."""
    pairs = ",".join(f"'{key}',{column} -> '$.{key}'" for key in fields)
    # Nested CASE avoids evaluating JSON operators on invalid JSON. The ->
    # operator preserves JSON booleans, unlike json_extract (true becomes 1).
    return (
        f"CASE WHEN json_valid({column}) THEN CASE WHEN json_type({column})='object' "
        f"THEN json_object({pairs}) END END AS metadata"
    )


RUN_PROJECTION = projection(
    "data",
    (
        "goal",
        "mode",
        "plan_revision",
        "source_ids",
        "artifact_ids",
        "current_artifact_ids",
    ),
)
FILE_PROJECTION = projection(
    "metadata",
    (
        "display_name",
        "format",
        "byte_count",
        "created_at",
        "run_id",
        "provenance",
    ),
)


class WorkSearchService:
    def __init__(self, runtime):
        self.store = runtime.store

    def _authority(self, conn, session_hash):
        require_access(self.store, conn, session_hash)
        # settings.version observes hide -> show as well as the current value.
        # The separate consent epoch conservatively invalidates delayed reads
        # across privacy/retention changes too, without reading retained content.
        epoch = conn.execute("SELECT epoch FROM personal_settings WHERE id=1").fetchone()[0]
        return self.store.settings(conn)["version"], epoch

    def _rows(self, conn):
        # One extra row proves each complete admitted corpus fits its cap. Do
        # this for all kinds, even when filtering, since linked fields affect hits.
        runs = conn.execute(
            f"SELECT id,state,version,updated_at,{RUN_PROJECTION} "
            "FROM agent_runs ORDER BY id LIMIT ?",
            (RUN_CAP + 1,),
        ).fetchall()
        sources = conn.execute(
            f"SELECT id,status,{FILE_PROJECTION} FROM private_files "
            "WHERE kind='sources' ORDER BY id LIMIT ?",
            (SOURCE_CAP + 1,),
        ).fetchall()
        artifacts = conn.execute(
            f"SELECT id,status,{FILE_PROJECTION} FROM private_files "
            "WHERE kind='artifacts' ORDER BY id LIMIT ?",
            (ARTIFACT_CAP + 1,),
        ).fetchall()
        if len(runs) > RUN_CAP or len(sources) > SOURCE_CAP or len(artifacts) > ARTIFACT_CAP:
            raise DomainError("WORK_SEARCH_CAPACITY_EXCEEDED", 409)
        return runs, sources, artifacts

    @staticmethod
    def _file(row, kind):
        if not isinstance(row["id"], str) or not ID.fullmatch(row["id"]):
            raise DomainError("WORK_SEARCH_METADATA_INVALID", 409)
        data = decode_projection(row["metadata"])
        fmt = data.get("format")
        item = {
            "kind": kind,
            "id": row["id"],
            "title": text(data.get("display_name"), 160, filename=True),
            "timestamp": timestamp(data.get("created_at")),
            "format": fmt if isinstance(fmt, str) and fmt in FORMATS else None,
            "byte_count": integer(data.get("byte_count")),
            "recorded_status": "verified" if row["status"] == "verified" else "unknown",
        }
        return item, data

    def _corpus(self, rows):
        runs, sources, artifacts = rows
        result, parents, source_names = [], {}, {}
        for row in sources:
            item, _ = self._file(row, "source")
            item["revision"] = 1
            source_names[item["id"]] = item["title"]
            result.append(item)
        for row in runs:
            if not isinstance(row["id"], str) or not ID.fullmatch(row["id"]):
                raise DomainError("WORK_SEARCH_METADATA_INVALID", 409)
            data = decode_projection(row["metadata"])
            item = {
                "kind": "run",
                "id": row["id"],
                "title": text(data.get("goal"), 4000),
                "timestamp": timestamp(row["updated_at"]),
                "state": row["state"] if row["state"] in RUN_STATES else "unknown",
                "version": integer(row["version"], 1),
                "mode": data.get("mode")
                if data.get("mode") in ("deterministic", "model")
                else None,
                "plan_revision": integer(data.get("plan_revision"), 1),
                "source_names": [
                    source_names[s]
                    for s in id_list(data.get("source_ids"), 12) or []
                    if source_names.get(s)
                ],
            }
            parents[row["id"]] = (item, data)
            result.append(item)
        for row in artifacts:
            item, data = self._file(row, "artifact")
            raw_parent = data.get("run_id")
            parent_id = (
                raw_parent
                if isinstance(raw_parent, str) and SCOPE_ID.fullmatch(raw_parent)
                else None
            )
            parent = parents.get(parent_id)
            membership = "unlinked" if raw_parent is None else "unknown"
            if parent:
                current = id_list(parent[1].get("current_artifact_ids"), ARTIFACT_CAP)
                history = id_list(parent[1].get("artifact_ids"), ARTIFACT_CAP)
                if current is not None and item["id"] in current:
                    membership = "current"
                elif current is not None and history is not None and item["id"] in history:
                    membership = "earlier"
            provenance = data.get("provenance")
            refs = []
            if isinstance(provenance, list) and len(provenance) <= 100:
                for ref in provenance:
                    sid = ref.get("source_id") if isinstance(ref, dict) else None
                    if (
                        isinstance(sid, str)
                        and sid in source_names
                        and source_names[sid]
                        and sid not in refs
                    ):
                        refs.append(sid)
            item.update(
                run_id=parent_id,
                current_linked_goal=parent[0]["title"] or None if parent else None,
                output_membership=membership,
                source_names=[source_names[s] for s in refs],
            )
            result.append(item)
        return sorted(result, key=lambda item: (item["kind"], item["id"]))

    @staticmethod
    def _match(item, query):
        if not query:
            return 5, [], "browse"
        own = [("id", normalize(item["id"])), ("title", normalize(item["title"]))]
        linked = [("source_name", normalize(name)) for name in item.get("source_names", [])]
        if item.get("current_linked_goal"):
            linked.append(("current_linked_goal", normalize(item["current_linked_goal"])))
        terms = query.split()
        fields = own + linked
        if not all(any(term in value for _, value in fields) for term in terms):
            return None
        matched = list(
            dict.fromkeys(name for name, value in fields if any(term in value for term in terms))
        )
        if query == own[0][1]:
            return 0, matched, "exact_id"
        if query == own[1][1]:
            return 1, matched, "exact_title"
        if any(query in value for _, value in own):
            return 2, matched, "phrase"
        if all(any(term in value for _, value in own) for term in terms):
            return 3, matched, "all_terms"
        return 4, matched, "linked_metadata"

    def search(self, payload: WorkSearchInput, *, session_hash):
        query = normalize(payload.query)
        with self.store.connection() as conn:
            conn.execute("PRAGMA query_only=ON")
            authority = self._authority(conn, session_hash)
            try:
                rows = self._rows(conn)
            except sqlite3.OperationalError as error:
                if "malformed JSON" in str(error):
                    raise DomainError("WORK_SEARCH_METADATA_INVALID", 409) from None
                raise
        corpus = self._corpus(rows)
        # Canonical compact projection changes invalidate a page even when an
        # unrelated hit changed. No query or private metadata is stored.
        snapshot = hashlib.sha256(
            encode(
                [
                    "lexical_v1",
                    query,
                    payload.kind,
                    session_hash,
                    authority,
                    corpus,
                ]
            ).encode()
        ).hexdigest()
        matches = []
        for item in corpus:
            if payload.kind != "all" and item["kind"] != payload.kind:
                continue
            match = self._match(item, query)
            if match is None:
                continue
            rank, fields, reason = match
            stamp = (
                datetime.fromisoformat(item["timestamp"].replace("Z", "+00:00")).timestamp()
                if item["timestamp"]
                else float("-inf")
            )
            matches.append(
                (
                    rank,
                    -stamp,
                    item["kind"],
                    item["id"],
                    {**item, "matched_fields": fields, "match_reason": reason},
                )
            )
        matches.sort(key=lambda item: item[:4])
        end = payload.offset + payload.limit
        result = WorkSearchResult(
            items=[match[4] for match in matches[payload.offset : end]],
            total=len(matches),
            snapshot=snapshot,
            next_offset=end if end < len(matches) else None,
        ).model_dump()
        # Reopen outside the corpus snapshot: hide/show, logout and elapsed
        # expiry must invalidate an in-flight read, not merely the next request.
        with self.store.connection() as conn:
            conn.execute("PRAGMA query_only=ON")
            if self._authority(conn, session_hash) != authority:
                raise DomainError("WORK_SEARCH_PRIVACY_CHANGED", 403)
        if payload.snapshot is not None and payload.snapshot != snapshot:
            raise DomainError("WORK_SEARCH_CHANGED", 409)
        return result


def work_search_routes(runtime, owner):
    router = APIRouter(prefix="/api/work", dependencies=[Depends(owner)])

    @router.post("/search", response_model=WorkSearchResult)
    def search(payload: WorkSearchInput, request: Request):
        return runtime.work_search.search(payload, session_hash=session_from_request(request))

    return router
